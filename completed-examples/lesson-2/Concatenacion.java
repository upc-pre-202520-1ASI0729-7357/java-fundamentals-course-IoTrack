public class Concatenacion {
    public static void main(String[] args) {
        String nombre = "Fabrizio";
        int edad = 22;
        System.out.println("Hola, mi nombre es " + nombre + " y tengo " + edad + " años.");

        double nota = 20;
        System.out.println(nombre + " obtuvo una nota de " + nota);
    }
}