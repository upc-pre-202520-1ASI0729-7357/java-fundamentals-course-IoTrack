public class Operacion {
    public static void main(String[] args) {
        int a = 5;
        int b = 3;

        int suma = a + b;
        int resta = a - b;
        int multiplicacion = a * b;

        System.out.println(suma);
        System.out.println(resta);
        System.out.println(multiplicacion);
    }
}